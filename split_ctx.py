def split_suffix(s):
    assert s.startswith(SEDE),s
    r=s[len(SEDE):];g=''
    m=re.search(r'(\(En blanco\)|Grupo Telefonica /.*|NO ESPECIFICO /.*)$',r)
    if m:
        g='' if m.group(1)=='(En blanco)' else m.group(1);r=r[:m.start()]
    if r in OVR:f,p=OVR[r]
    elif r.startswith('**PRIVADO**'):f,p='**PRIVADO**',r[11:]
    else:
        n=len(r);f=p=None
        if n%2==0 and r[:n//2]==r[n//2:]:f,p=r[:n//2],r[n//2:]
        else:
            tok=r.split(' ')[0]
            for k in range(len(tok)+1,n):
                if r.startswith(tok,k) and k>=3:f,p=r[:k],r[k:];break
        if f is None:f,p=r,''
    return f,p,g
